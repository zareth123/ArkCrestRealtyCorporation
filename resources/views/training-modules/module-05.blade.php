    <div class="crs-pin-detail is-open" data-detail="m5-fiduciary-0"><strong>Confidentiality</strong><p>Whatever your client tells you privately — including their maximum budget or how motivated they really are — stays with you. It's not something you casually reveal to speed up a negotiation.</p></div>
    <div class="crs-pin-detail" data-detail="m5-fiduciary-1"><strong>Loyalty</strong><p>You negotiate fiercely on your client's behalf, even when it would be faster or easier for you personally to just meet the other side halfway.</p></div>
    <div class="crs-pin-detail" data-detail="m5-fiduciary-2"><strong>Honest Accounting</strong><p>Every peso that passes through you — commissions, fees, reservation payments — is tracked and disclosed accurately, with nothing quietly unaccounted for.</p></div>

    <div class="crs-scenario">
