    <div class="crs-pin-detail is-open" data-detail="m5-docs-0"><strong>Purchase Agreement</strong><p>The document that legally binds both parties to the sale — price, terms, and deadlines. Once signed, it isn't just a formality; it's enforceable.</p></div>
    <div class="crs-pin-detail" data-detail="m5-docs-1"><strong>Agency Disclosure</strong><p>Clarifies exactly who you represent in the transaction — the buyer, the seller, or both — so there's no confusion later about whose interests you're protecting.</p></div>
    <div class="crs-pin-detail" data-detail="m5-docs-2"><strong>Addendum</strong><p>Formally amends terms after the original agreement was signed — for example, an extended deadline or a revised price. Verbal agreements don't count; if it isn't in an addendum, it isn't binding.</p></div>

    <p>A useful habit: before any document leaves your hands for signing, read every field once, out loud if needed, as if you were the one whose deposit was on the line. It's a small discipline that catches most costly mistakes before they become somebody's problem.</p>
    <div class="crs-scenario">
        <strong>🇵🇭 Philippine Scenario</strong>
        <p>A Reservation Agreement lists the down payment deadline as "within 30 days" but the actual signed date field was left blank. Weeks later, the developer disputes when the clock started, putting the buyer's reservation fee at risk. A five-second check at signing would have prevented the entire dispute.</p>
    </div>
    <div class="crs-takeaway-line"><strong>Core Takeaway:</strong> A single missing initial or an incorrectly typed deadline can cost a client their earnest money deposit or kill a deal entirely. Attention to detail is non-negotiable.</div>
