    <span class="crs-sub-label">4.2.1 A Feature Is a Spec. A Benefit Is a Feeling.</span>
    <p>A <strong>feature</strong> is a spec. A <strong>benefit</strong> is what that spec actually does for the client's life. Your job on a tour is to translate one into the other, every single time you point something out. Tap each card below to see the difference in practice.</p>
    <div class="crs-compare-grid">
        <div class="crs-compare-card">
            <div class="crs-compare-head"><strong>📋 Feature</strong><svg class="crs-compare-toggle" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 4v16m8-8H4"/></svg></div>
            <div class="crs-compare-body"><p>"This unit has a large kitchen island." A true, accurate spec — but it doesn't make anyone feel anything.</p></div>
        </div>
        <div class="crs-compare-card">
            <div class="crs-compare-head"><strong>💡 Benefit</strong><svg class="crs-compare-toggle" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 4v16m8-8H4"/></svg></div>
            <div class="crs-compare-body"><p>"A place where your kids can do homework while you prepare dinner without feeling crowded." Same island — now it's a benefit, and it's the benefit that actually sells.</p></div>
        </div>
    </div>
    <p>A simple habit builds this reflex over time: after describing any feature out loud, silently ask yourself "so what?" — and answer that question for the client before they have to ask it themselves.</p>
    <div class="crs-scenario">
        <strong>🇵🇭 Philippine Scenario</strong>
        <p>Instead of saying "this unit has a balcony," you say, "this is where you'll have your morning coffee before the Manila heat sets in." The buyer isn't picturing a balcony anymore — they're picturing their own morning routine, which is a much harder thing to walk away from.</p>
    </div>
    <div class="crs-takeaway-line"><strong>Core Takeaway:</strong> Always sell the benefit, not just the feature. Translate architectural specs into lifestyle upgrades the client can picture themselves living.</div>
</article>

