    <span class="crs-sub-label">3.1.1 Checklist Questions vs. Discovery Questions</span>
    <p>It's tempting to jump straight into close-ended questions like "Do you want 3 bedrooms?" — but questions like that only confirm a checklist, they don't tell you why. Tap each card to compare the two approaches.</p>
    <div class="crs-compare-grid">
        <div class="crs-compare-card">
            <div class="crs-compare-head"><strong>❌ Checklist Question</strong><svg class="crs-compare-toggle" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 4v16m8-8H4"/></svg></div>
            <div class="crs-compare-body"><p>"Do you want 3 bedrooms?" gets you a yes/no answer and nothing else. It confirms a box on a spec sheet but tells you nothing about why that number matters to them.</p></div>
        </div>
        <div class="crs-compare-card">
            <div class="crs-compare-head"><strong>✅ Discovery Question</strong><svg class="crs-compare-toggle" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 4v16m8-8H4"/></svg></div>
            <div class="crs-compare-body"><p>"Walk me through how you use your current space on a weekend" is open-ended and lifestyle-focused. A single question like this can surface far more than a bedroom count ever will.</p></div>
        </div>
    </div>
    <p>A client's initial request is almost always just the surface. Deep discovery questions uncover the <strong>emotional drivers</strong> underneath — the need for security, status, or convenience — that actually decide which property they'll say yes to in the end. The skill isn't asking more questions, it's asking questions that a spec sheet can't answer for them.</p>
    <div class="crs-scenario">
        <strong>🇵🇭 Philippine Scenario</strong>
        <p>A client tells you they want "a bigger condo." Instead of pulling up every larger unit in your inventory, you ask what a typical weekend looks like at home. They mention their in-laws visit often and the current unit has nowhere for guests to sit comfortably. Now you're not just shopping for square meters — you're shopping for a layout with a proper living area, which narrows your search dramatically.</p>
    </div>
    <div class="crs-takeaway-line"><strong>Core Takeaway:</strong> The client's initial request is often just the surface. Deep discovery questions uncover the emotional drivers — security, status, or convenience — behind the purchase.</div>
